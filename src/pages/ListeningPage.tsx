import { useEffect, useMemo, useState } from 'react'
import { useParams } from 'react-router-dom'
import clsx from 'clsx'
import { LISTENINGS } from '../content'
import { Card, PageTitle, Notice } from '../components/ui'
import { ExerciseRunner, ResultsSummary, type RunnerResult } from '../components/ExerciseRunner'
import { addXp, recordAttempt } from '../lib/repo'
import { XP } from '../lib/stats'
import { speakSequence, stop, ttsAvailable } from '../lib/tts'
import { useStudyTimer } from '../hooks/hooks'
import type { ListeningItem } from '../content/types'

export default function ListeningPage() {
  const { id } = useParams()
  const l = LISTENINGS.find((x) => x.id === id)
  if (!l) return <Notice tone="error">Audio not found.</Notice>
  return <Player key={l.id} l={l} />
}

function Player({ l }: { l: ListeningItem }) {
  useStudyTimer()
  const [rate, setRate] = useState(1)
  const [playing, setPlaying] = useState(false)
  const [line, setLine] = useState(-1)
  const [plays, setPlays] = useState(0)
  const [step, setStep] = useState<'listen' | 'quiz' | 'done'>('listen')
  const [results, setResults] = useState<RunnerResult[]>([])
  const speakers = useMemo(() => [...new Set(l.lines.map((x) => x.speaker))], [l])
  useEffect(() => () => stop(), [])

  const play = () => {
    setPlaying(true)
    setPlays(plays + 1)
    speakSequence(l.lines.map((x) => ({ text: x.text, speaker: speakers.indexOf(x.speaker) })), rate, setLine, () => { setPlaying(false); setLine(-1) })
  }

  return (
    <div>
      <PageTitle back="/practice" title={l.title} subtitle={`${l.level} · ${l.kind}`} />
      {step !== 'done' && (
        <Card className="mb-4">
          {ttsAvailable() ? (
            <div className="flex flex-wrap items-center gap-3">
              <button className="btn-primary" onClick={playing ? () => { stop(); setPlaying(false) } : play}>{playing ? '■ Stop' : plays ? '↺ Listen again' : '▶ Play'}</button>
              <div className="flex gap-1" role="group" aria-label="Speed">
                {[0.75, 0.9, 1, 1.15].map((r) => <button key={r} onClick={() => setRate(r)} aria-pressed={rate === r} className={clsx('rounded-lg px-2.5 py-1 text-sm', rate === r ? 'bg-ink-800 text-white dark:bg-ink-200 dark:text-ink-900' : 'bg-ink-100 dark:bg-ink-800')}>{r}×</button>)}
              </div>
              <span className="text-xs text-ink-400">{speakers.length} speaker{speakers.length > 1 ? 's' : ''} · played {plays}×</span>
            </div>
          ) : (
            <Notice tone="warn">No speech voice on this device — read the transcript instead.<div className="mt-2"><Transcript lines={l.lines} line={line} /></div></Notice>
          )}
          <p className="mt-3 text-xs text-ink-400">Audio is generated by your device's voice and works offline. The transcript is shown after the questions.</p>
        </Card>
      )}
      {step === 'listen' && <button className="btn-primary w-full" onClick={() => setStep('quiz')} disabled={plays === 0 && ttsAvailable()}>Answer the questions →</button>}
      {step === 'quiz' && (
        <Card>
          <ExerciseRunner items={l.questions.map((item) => ({ item }))}
            onAnswer={(x) => recordAttempt({ skill: 'listening', level: l.level, source: 'listening', refId: l.id, itemId: x.item.id, correct: x.correct }).then(() => undefined)}
            onFinish={async (rs) => { await addXp(XP.listeningDone); setResults(rs); setStep('done') }} />
        </Card>
      )}
      {step === 'done' && (
        <div className="space-y-4">
          <Card><ResultsSummary results={results}><button className="btn-ghost" onClick={() => { setStep('listen'); setPlays(0) }}>Listen again</button></ResultsSummary></Card>
          <Card><p className="label mb-2">Transcript</p>{ttsAvailable() && <button className="btn-ghost mb-2" onClick={play}>▶ Play with transcript</button>}<Transcript lines={l.lines} line={line} /></Card>
          <Card><p className="label mb-2">Vocabulary</p><ul className="space-y-1 text-sm">{l.vocab.map((v) => <li key={v.word}><b>{v.word}</b> — {v.def}</li>)}</ul></Card>
        </div>
      )}
    </div>
  )
}

function Transcript({ lines, line }: { lines: ListeningItem['lines']; line: number }) {
  return (
    <ol className="space-y-2">
      {lines.map((x, k) => <li key={k} className={clsx('rounded-lg px-2 py-1', k === line && 'bg-brand-50 dark:bg-brand-900/30')}><span className="font-semibold">{x.speaker}:</span> {x.text}</li>)}
    </ol>
  )
}
